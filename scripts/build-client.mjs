#!/usr/bin/env node
/**
 * 构建 dsh-pin 客户端 bundle。
 *
 * - 把 lib/pin-core.mjs 的纯函数内联进 src/client-src.js 的占位注释；
 * - 包进 window.__ModuleLoader__.load({ id, factory }) 外壳；
 * - 写入 lib/client.js（提交物，勿手改）。
 *
 * 用法：
 *   node scripts/build-client.mjs          # 重新生成
 *   node scripts/build-client.mjs --check  # 只校验已提交 bundle 与源码同步
 */
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const PACKAGE_NAME = manifest.name;
const CORE_PLACEHOLDER = "/*__PIN_CORE__*/";

function stripModuleSyntax(source) {
  return source
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|var|class)/gm, "")
    .replace(/^export\s+\{[^}]*\};?\s*$/gm, "")
    .trim();
}

function build() {
  const corePath = join(root, "lib", "pin-core.mjs");
  const sourcePath = join(root, "src", "client-src.js");
  const core = stripModuleSyntax(readFileSync(corePath, "utf8"));
  const body = readFileSync(sourcePath, "utf8");

  if (!body.includes(CORE_PLACEHOLDER)) {
    throw new Error(`src/client-src.js is missing the ${CORE_PLACEHOLDER} placeholder`);
  }

  const withCore = body.replace(CORE_PLACEHOLDER, `// ── inlined from lib/pin-core.mjs ──\n${core}`);
  const indented = withCore
    .split("\n")
    .map((line) => (line === "" ? "" : `    ${line}`))
    .join("\n");

  const bundle = `/* dsh-pin client bundle — generated by scripts/build-client.mjs; do not edit by hand. */
window.__ModuleLoader__.load({
  id: "${PACKAGE_NAME}",
  factory: (require) => {
${indented}

    return { apply, inject };
  },
});
`;

  // 语法校验：包壳只引用 window（Node 下不执行，只解析）。
  const checkPath = join(tmpdir(), `dsh-pin-client-${process.pid}.js`);
  writeFileSync(checkPath, bundle);
  try {
    execFileSync(process.execPath, ["--check", checkPath], { stdio: "pipe" });
  } finally {
    try {
      rmSync(checkPath, { force: true });
    } catch {
      /* best effort */
    }
  }

  return bundle;
}

const checkOnly = process.argv.includes("--check");
const outputPath = join(root, "lib", "client.js");
const bundle = build();

if (checkOnly) {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    current = "";
  }
  if (current !== bundle) {
    console.error("lib/client.js is out of date; run: node scripts/build-client.mjs");
    process.exit(1);
  }
  console.log("lib/client.js is up to date");
} else {
  writeFileSync(outputPath, bundle);
  console.log(`wrote ${outputPath} (${bundle.length} bytes)`);
}
